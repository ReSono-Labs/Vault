def test_canonical_input_multibyte_boundary_includes_context_and_does_not_truncate():
    req = request(context_sources=())
    # Independently compute the JSON section overhead for an empty user string.
    overhead = len(b'{"context_sources":[],"phase":"provisional","user_input":""}')
    text = "é" * ((65536 - overhead) // 2) + "a" * ((65536 - overhead) % 2)
    req = replace(req, input_text=text, input_identity=replace(req.input_identity, input_fingerprint=sha256(text.encode()).hexdigest()))
    assert len(project_request(req)["input"].encode()) == 65536
    assert json.loads(project_request(req)["input"])["user_input"] == text
    with pytest.raises(InputError):
        project_request(replace(req, input_text=text + "a", input_identity=replace(req.input_identity, input_fingerprint=sha256((text + "a").encode()).hexdigest())))
    with pytest.raises(InputError):
        project_request(replace(request(), context_sources=(EvidenceRef("s", "memory", "user_asserted", "x" * 65536),)))


@pytest.mark.parametrize("when", ["before", "after"])
@pytest.mark.parametrize("reason", ["canceled", "timeout", "stale"])
def test_invalidated_completion_is_never_decoded_or_selected(when, reason):
    clock, cancellation = Clock(), Cancellation()
    state = {"current": True}

    def invalidate():
        if reason == "canceled":
            cancellation.is_cancelled = True
        elif reason == "timeout":
            clock.value = 20.0
        else:
            state["current"] = False

    if when == "before":
        invalidate()
    # Malformed object: if decoded first it would produce invalid_response, not guard reason.
    transport = Transport(reply={"bad": object()}, action=invalidate if when == "after" else None)
    result = choose(transport=transport, clock=clock, cancellation=cancellation,
                    current=lambda token: state["current"])
    assert result.reason == reason
    assert len(transport.calls) == (0 if when == "before" else 1)


