class Clock:
    value = 10.0

    def now(self):
        return self.value


class Cancellation:
    is_cancelled = False


def request(**changes):
    candidates = (CandidateChoice("invoice", "decision-invoice", 3, "Read invoice payment status, not balance."),
                  CandidateChoice("balance", "decision-balance", 2, "Read customer outstanding balance, not one invoice."))
    text = "Did ABC pay invoice 482?"
    initial = SelectionRequest(
        "request-1", ScopedPrincipalRef("user", "workspace", "login"),
        InputIdentity("conversation", "segment", "utterance", 7, None, sha256(text.encode()).hexdigest()),
        "provisional", text,
        (EvidenceRef("memory-1", "memory", "user_asserted", "ABC means ABC Supply."),),
        "context-v1", candidates, candidate_set_fingerprint(candidates),
        "capabilities-v1", "generation-v1", 1, True,
    )
    return replace(initial, **changes)


def response():
    # Independently hand-written official choice shape, not generated by the mapper.
    return {"answers": [{"type": "choice", "name": "workflow", "choice": "invoice",
                         "confidence": 0.6, "probabilities": [
                             {"value": "invoice", "probability": 0.85},
                             {"value": "balance", "probability": 0.1},
                             {"value": "__fallback__", "probability": 0.05}]}],
            "model": "gpt-6-luna", "usage": {"input_tokens": 100, "output_tokens": 0, "total_tokens": 100,
                                             "input_tokens_details": {"cached_tokens": 0, "cache_write_tokens": 0},
                                             "output_tokens_details": {"reasoning_tokens": 0}}}


class Transport:
    def __init__(self, reply=None, action=None, error=None):
        self.reply = response() if reply is None else reply
        self.action = action
        self.error = error
        self.calls = []

    def evaluate(self, payload, *, timeout_seconds):
        self.calls.append((deepcopy(payload), timeout_seconds))
        if self.action:
            self.action()
        if self.error:
            raise self.error
        return self.reply


def choose(req=None, *, transport=None, clock=None, cancellation=None, current=None, deadline=20.0):
    return DecisionSelector(transport=transport, clock=clock or Clock()).choose(
        req or request(), deadline=deadline, cancellation=cancellation or Cancellation(),
        is_current=current or (lambda token: True),
    )


