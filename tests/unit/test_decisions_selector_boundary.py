def test_valid_selection_is_exact_frozen_mapping_not_probability_threshold():
    transport = Transport()
    tokens = []
    result = choose(transport=transport, current=lambda token: tokens.append(token) or True)
    assert isinstance(result, Selected)
    assert (result.definition_id, result.version, result.confidence) == ("decision-invoice", 3, 0.6)
    assert result.probabilities[0].probability == 0.85  # Not equal to confidence.
    assert result.usage.input_tokens == 100 and result.model == "gpt-6-luna"
    assert len(transport.calls) == 1 and transport.calls[0][1] == 10.0
    assert all(token == ValidationToken(7, request().input_identity.input_fingerprint,
                                       "context-v1", request().candidate_set_fingerprint,
                                       "capabilities-v1", "generation-v1") for token in tokens)
    assert result.request_identity.scope == request().scope
    with pytest.raises(FrozenInstanceError):
        result.version = 4
    with pytest.raises(FrozenInstanceError):
        result.probabilities[0].probability = 0.0
    transport.reply["answers"][0]["probabilities"][0]["probability"] = 0.0
    assert result.probabilities[0].probability == 0.85


def test_no_threshold_sum_tolerance_or_equality_policy_is_invented():
    reply = response()
    reply["answers"][0]["confidence"] = 0
    for probability in reply["answers"][0]["probabilities"]:
        probability["probability"] = 1
    result = choose(transport=Transport(reply))
    assert isinstance(result, Selected) and result.confidence == 0


