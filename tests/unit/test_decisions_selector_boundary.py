@pytest.mark.parametrize("defect", ["bool_choice", "unknown_choice", "wrong_name", "wrong_type",
                                     "missing_option", "duplicate_option", "unknown_option", "bool_option",
                                     "missing_confidence", "missing_probability", "multiple_answers",
                                     "missing_answers", "non_object", "bad_usage", "bool_usage", "bad_model",
                                     "negative_usage", "bad_usage_details", "depth", "nodes", "size", "cycle"])
def test_malformed_response_falls_back(defect):
    reply = response()
    answer = reply["answers"][0]
    if defect in {"bool_choice", "unknown_choice", "wrong_name", "wrong_type"}:
        field, value = {"bool_choice": ("choice", True), "unknown_choice": ("choice", "execute_anything"),
                        "wrong_name": ("name", "not_workflow"), "wrong_type": ("type", "predicate")}[defect]
        answer[field] = value
    elif defect == "missing_option":
        answer["probabilities"].pop()
    elif defect in {"duplicate_option", "unknown_option", "bool_option"}:
        answer["probabilities"][1]["value"] = {"duplicate_option": "invoice", "unknown_option": "unknown", "bool_option": True}[defect]
    elif defect == "missing_confidence":
        del answer["confidence"]
    elif defect == "missing_probability":
        del answer["probabilities"][0]["probability"]
    elif defect == "multiple_answers":
        reply["answers"].append(deepcopy(answer))
    elif defect == "missing_answers":
        del reply["answers"]
    elif defect == "non_object":
        reply = []
    elif defect == "bad_usage":
        reply["usage"] = "usage"
    elif defect == "bool_usage":
        reply["usage"]["input_tokens"] = True
    elif defect == "negative_usage":
        reply["usage"]["input_tokens"] = -1
    elif defect == "bad_model":
        reply["model"] = "m" * 257
    elif defect == "bad_usage_details":
        reply["usage"]["input_tokens_details"] = []
    elif defect == "depth":
        nested = []
        reply["extra"] = nested
        for _ in range(33):
            child = []
            nested.append(child)
            nested = child
    elif defect == "nodes":
        reply["extra"] = [0] * 50000
    elif defect == "size":
        reply["extra"] = "x" * 1048576
    else:
        reply["extra"] = reply
    assert choose(transport=Transport(reply)).reason == "invalid_response"


