def test_fingerprint_covers_order_description_id_version_and_actual_text():
    req = request()
    independently_encoded = json.dumps({"selector_contract_version": 1, "candidates": [
        {"value": "invoice", "definition_id": "decision-invoice", "definition_version": 3,
         "applicability_description": "Read invoice payment status, not balance."},
        {"value": "balance", "definition_id": "decision-balance", "definition_version": 2,
         "applicability_description": "Read customer outstanding balance, not one invoice."},
    ]}, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
    assert req.candidate_set_fingerprint == sha256(independently_encoded).hexdigest()
    variants = [tuple(reversed(req.candidate_set))]
    for field, value in (("definition_id", "different"), ("definition_version", 4),
                         ("applicability_description", "changed"), ("value", "different")):
        variants.append((replace(req.candidate_set[0], **{field: value}), req.candidate_set[1]))
    for changed in variants:
        with pytest.raises(InputError):
            project_request(replace(req, candidate_set=changed))
    with pytest.raises(InputError):
        project_request(replace(req, input_text="changed text"))


