@pytest.mark.parametrize("reason", ["canceled", "timeout", "stale"])
def test_final_publication_is_rechecked_after_bounded_decode(monkeypatch, reason):
    from app.vault_runtime.decision_routing import selector

    clock, cancellation = Clock(), Cancellation()
    state = {"current": True}
