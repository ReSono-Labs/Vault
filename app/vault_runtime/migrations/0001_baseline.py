"""0001 baseline: the schema that build_local_app produced at every start before migrations.

The statements are frozen in ``0001_baseline.sql`` (FREEZE-0001): exactly what this migration
executed, in order, when it still called the module DDL functions (composition.py's order, every
feature flag on). Later edits to those modules therefore cannot change what 0001 does. All
statements are idempotent: on an existing database this fills gaps and is then recorded as applied.
Two steps depend on existing state and stay code here: the Procrastinate queue schema (only when
its tables are missing) and the one-time move of workspace file projections to disk.

Do not edit this file or 0001_baseline.sql; the checksum covers both. Add a new migration.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from app.vault_runtime.migrations.runner import context

_LOG = logging.getLogger(__name__)
_SQL = Path(__file__).with_suffix(".sql")
_MARKER = "-- @"


def _items(text: str) -> list[tuple[str, str, list[str] | None, str]]:
    """(kind, name, parameters, body) per marker, in file order; the header before the first marker is skipped."""
    items: list[tuple[str, str, list[str] | None, str]] = []
    current: list | None = None
    for line in text.splitlines(keepends=True):
        if line.startswith(_MARKER):
            kind, _, rest = line[len(_MARKER):].rstrip("\n").partition(" ")
            if kind == "statement":
                current = ["statement", "", json.loads(rest) if rest else None, []]
            elif kind == "step":
                current = ["step", rest, None, []]
            else:
                raise ValueError(f"Unknown 0001 marker: {line!r}")
            items.append(current)
        elif current is not None:
            current[3].append(line)
    return [(kind, name, params, "".join(body)[:-1]) for kind, name, params, body in items]


def _procrastinate_schema(cursor, schema: str) -> None:  # was BackgroundJobs.ensure_schema
    cursor.execute("SELECT to_regclass('vault_background_queue.procrastinate_jobs')")
    if cursor.fetchone()[0] is None:
        cursor.execute("SELECT current_setting('search_path')")
        previous = cursor.fetchone()[0]
        cursor.execute("SET LOCAL search_path TO vault_background_queue, public")
        cursor.execute(schema)
        cursor.execute("SELECT set_config('search_path', %s, true)", (previous,))


def _workspace_file_projections(cursor) -> None:  # was WorkspaceFileRepository.ensure_schema(storage=...)
    cursor.execute("SELECT to_regclass('vault_private.vault_workspace_file_projections')")
    if cursor.fetchone()[0] is not None:
        storage = context().get("storage")
        if storage is None:
            raise RuntimeError("Migration 0001 needs workspace storage to move legacy file projections")
        from app.vault_runtime.workspace_files.repository import WorkspaceFileRepository

        migrated = WorkspaceFileRepository._migrate_legacy_projections(cursor, storage=storage)
        if migrated:
            _LOG.info("Migrated %s legacy workspace file projection(s) to disk.", migrated)


def apply(cursor) -> None:
    for kind, name, params, body in _items(_SQL.read_text()):
        if kind == "statement":
            cursor.execute(body, params)
        elif name == "procrastinate_schema":
            _procrastinate_schema(cursor, body)
        elif name == "workspace_file_projections":
            _workspace_file_projections(cursor)
        else:
            raise ValueError(f"Unknown 0001 step: {name}")
