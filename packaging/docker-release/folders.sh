#!/bin/sh
# Makes the installing user's home folder and drives visible to Vault.
# Vault uses none of it until someone gives access in the web interface.
#
#   folders.sh compose OUTPUT [BRIDGE_SERVICE]
#                               write a Docker Compose override (Linux, macOS)
#   folders.sh native           print systemd drop-in lines for the native Linux install
#
# No questions are asked. Windows uses vault.ps1 instead.
set -eu

mode=${1:-}
output=${2:-}
bridge_service=${3:-bridge}
# Vault's own Docker network on Linux and its gateway, where Link's connector listens for
# Vault's Agent Network calls (Link's agents/vault/manifest.toml [container_gateway] bind).
link_subnet=198.19.235.0/24
link_gateway=198.19.235.1

fail() {
  printf '%s\n' "$*" >&2
  exit 1
}

case "$(uname -s)" in
  Linux) os=linux ;;
  Darwin) os=macos ;;
  *) fail "This computer type isn't supported by folders.sh." ;;
esac
if [ "$os" = linux ] && grep -qi microsoft /proc/version 2>/dev/null; then
  fail "On Windows, run vault.ps1 from PowerShell instead."
fi

# The person installing, even when run through sudo.
if [ "$(id -u)" -eq 0 ] && [ -n "${SUDO_USER:-}" ] && [ "${SUDO_USER}" != root ]; then
  user=$SUDO_USER
  uid=${SUDO_UID:-$(id -u "$user")}
  gid=${SUDO_GID:-$(id -g "$user")}
  if command -v getent >/dev/null 2>&1; then
    home=$(getent passwd "$user" | cut -d: -f6)
  else
    home=$(eval printf '%s' "~$user")
  fi
else
  user=$(id -un)
  uid=$(id -u)
  gid=$(id -g)
  home=${HOME:-}
fi
[ -n "$home" ] && [ -d "$home" ] || fail "Vault couldn't find your home folder."
home=$(CDPATH= cd -- "$home" && pwd -P)

# Documents, relative to home (it can be renamed or translated on Linux).
documents=Documents
if [ "$os" = linux ] && [ "$(id -u)" -ne 0 ] && command -v xdg-user-dir >/dev/null 2>&1; then
  detected=$(xdg-user-dir DOCUMENTS 2>/dev/null || true)
  case "$detected" in
    "$home"/?*) documents=${detected#"$home"/} ;;
  esac
fi

# Drive locations: "id|label|host path|container path"
drives=""
add_drive() {
  if [ -d "$3" ]; then
    resolved=$(CDPATH= cd -- "$3" && pwd -P)
    drives="${drives}$1|$2|$resolved|$4
"
  fi
}
if [ "$os" = linux ]; then
  if [ -d "/media/$user" ]; then
    add_drive media Drives "/media/$user" /host/drives/media
  else
    add_drive media Drives /media /host/drives/media
  fi
  add_drive run-media "Removable drives" "/run/media/$user" /host/drives/run-media
  add_drive mnt "Other drives" /mnt /host/drives/mnt
else
  add_drive volumes Drives /Volumes /host/drives/volumes
fi

json_string() {
  printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"
}

# $1 = "container" or "host": which paths go in the location list.
locations_json() {
  if [ "$1" = container ]; then home_path=/host/home; else home_path=$home; fi
  printf '[{"id":"home","label":"Home","path":%s,"kind":"home"}' "$(json_string "$home_path")"
  printf '%s' "$drives" | while IFS='|' read -r id label host target; do
    [ -n "$id" ] || continue
    if [ "$1" = container ]; then path=$target; else path=$host; fi
    printf ',{"id":"%s","label":%s,"path":%s,"kind":"drives"}' "$id" "$(json_string "$label")" "$(json_string "$path")"
  done
  printf ']'
}

yaml_string() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

write_compose() {
  [ -n "$output" ] || fail "Usage: folders.sh compose OUTPUT"
  set_user=no
  if [ "$os" = linux ] && [ "$uid" -ne 0 ]; then
    set_user=yes
  fi
  temporary="$output.tmp.$$"
  {
    printf '%s\n' '# Generated by folders.sh on install. Do not edit; it is rewritten on install, update and start.'
    printf '%s\n' 'services:'
    if [ "$set_user" = yes ]; then
      printf '%s\n' '  initialize:' '    environment:'
      printf '      RESONO_VAULT_RUNTIME_UID: "%s"\n      RESONO_VAULT_RUNTIME_GID: "%s"\n' "$uid" "$gid"
    fi
    printf '%s\n' '  vault:'
    if [ "$set_user" = yes ]; then
      printf '    user: "%s:%s"\n' "$uid" "$gid"
    fi
    if [ "$os" = linux ]; then
      # Linux: host.docker.internal is the gateway of Vault's own network (pinned below), where
      # Link's connector serves Vault's Agent Network gateway (port 8769). Docker's default
      # host-gateway is docker0, which Link's sandboxed service cannot look up, so Vault could
      # not call other agents. macOS and Windows keep Docker Desktop's host-gateway.
      printf '%s\n' '    extra_hosts: !override' "      - \"host.docker.internal:$link_gateway\""
    fi
    printf '%s\n' '    environment:' '      HOME: /var/lib/resono-vault'
    printf '      RESONO_VAULT_DEVICE_LOCATIONS: %s\n' "$(yaml_string "$(locations_json container)")"
    printf '      RESONO_VAULT_DOCUMENTS_FOLDER: %s\n' "$(yaml_string "$documents")"
    printf '%s\n' '    volumes:'
    printf '      - type: bind\n        source: %s\n        target: /host/home\n' "$(yaml_string "$home")"
    printf '%s' "$drives" | while IFS='|' read -r id label host target; do
      [ -n "$id" ] || continue
      printf '      - type: bind\n        source: %s\n        target: %s\n' "$(yaml_string "$host")" "$target"
      if [ "$os" = linux ]; then
        printf '%s\n' '        bind:' '          propagation: rslave'
      fi
    done
    if [ "$set_user" = yes ]; then
      printf '  %s:\n' "$bridge_service"
      printf '    user: "%s:%s"\n' "$uid" "$gid"
    fi
    if [ "$os" = linux ]; then
      # 198.19.235.0/24: RFC 2544's benchmarking block, never a home or office network and
      # never one of Docker's own address pools. Link's Vault manifest names 198.19.235.1.
      printf '%s\n' 'networks:' '  default:' '    ipam:' '      config:'
      printf '        - subnet: %s\n          gateway: %s\n' "$link_subnet" "$link_gateway"
    fi
  } > "$temporary"
  chmod 0600 "$temporary"
  mv "$temporary" "$output"
}

systemd_quote() {
  # Double-quoted systemd value: escape backslashes and quotes, double % (specifier character).
  printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g; s/%/%%/g')"
}

print_native() {
  [ "$uid" -ne 0 ] || fail "Run the installer with sudo from your own account, not as root."
  printf 'User=%s\n' "$user"
  printf 'Group=%s\n' "$(id -gn "$user")"
  printf 'Environment=%s\n' "$(systemd_quote "RESONO_VAULT_DEVICE_LOCATIONS=$(locations_json host)")"
  printf 'Environment=%s\n' "$(systemd_quote "RESONO_VAULT_DOCUMENTS_FOLDER=$documents")"
  printf 'ReadWritePaths=%s\n' "$(systemd_quote "-$home")"
  printf '%s' "$drives" | while IFS='|' read -r id label host target; do
    [ -n "$id" ] || continue
    printf 'ReadWritePaths=%s\n' "$(systemd_quote "-$host")"
  done
}

case "$mode" in
  compose) write_compose ;;
  native) print_native ;;
  *) fail "Usage: folders.sh {compose OUTPUT|native}" ;;
esac
