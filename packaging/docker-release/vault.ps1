<#
.SYNOPSIS
  Install and run ReSono Vault on Windows with Docker Desktop. No WSL or Ubuntu steps needed.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\vault.ps1 install
#>
param(
    [Parameter(Position = 0)]
    [ValidateSet('install', 'update', 'setup', 'enable-lan', 'start', 'stop', 'status', 'logs', 'uninstall')]
    [string]$Command = 'install',

    [Parameter(Position = 1)]
    [string]$Address = ''
)

$ErrorActionPreference = 'Stop'
$PackageDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$EnvFile = Join-Path $PackageDir 'vault.env'
$ComposeFile = Join-Path $PackageDir 'compose.yml'
$FoldersFile = Join-Path $PackageDir 'compose.folders.yml'
$Utf8 = New-Object System.Text.UTF8Encoding($false)

function Write-Utf8File([string]$Path, [string]$Text) {
    $temporary = "$Path.tmp"
    [System.IO.File]::WriteAllText($temporary, $Text, $Utf8)
    Move-Item -Force $temporary $Path
}

function Invoke-Compose {
    $arguments = @('compose', '--env-file', $EnvFile, '-f', $ComposeFile)
    if (Test-Path $FoldersFile) { $arguments += @('-f', $FoldersFile) }
    $arguments += $args
    & docker @arguments
    if ($LASTEXITCODE -ne 0) { throw "Docker Compose failed (exit $LASTEXITCODE)." }
}

function Assert-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw 'Docker Desktop is not installed. Install it from https://www.docker.com/products/docker-desktop/ and try again.'
    }
    & docker info *> $null
    if ($LASTEXITCODE -ne 0) { throw 'Start Docker Desktop and try again.' }
}

function Get-LanAddress {
    $route = Get-NetRoute -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue |
        Sort-Object RouteMetric | Select-Object -First 1
    if (-not $route) { return $null }
    $ip = Get-NetIPAddress -InterfaceIndex $route.ifIndex -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($ip) { return $ip.IPAddress }
    return $null
}

function Set-Lan([string]$Requested) {
    $lan = if ($Requested) { $Requested } else { Get-LanAddress }
    $parsed = $null
    if (-not $lan -or -not [System.Net.IPAddress]::TryParse($lan, [ref]$parsed) -or
        $parsed.AddressFamily -ne [System.Net.Sockets.AddressFamily]::InterNetwork) {
        throw "Vault could not detect this computer's local address. Run: .\vault.ps1 enable-lan 192.168.1.50"
    }
    $lines = Get-Content $EnvFile | Where-Object { $_ -notmatch '^VAULT_BIND_ADDRESS=' -and $_ -notmatch '^VAULT_TLS_HOSTS=' }
    $lines += 'VAULT_BIND_ADDRESS=0.0.0.0'
    $lines += "VAULT_TLS_HOSTS=localhost,127.0.0.1,$lan"
    Write-Utf8File $EnvFile (($lines -join "`n") + "`n")
    return $lan
}

function ConvertTo-YamlString([string]$Value) {
    return "'" + $Value.Replace("'", "''") + "'"
}

# Your user folder and drives become visible to Vault. Nothing is used until you
# give access in the web interface. Rewritten each time so new drives are picked up.
function Set-Folders {
    $userProfile = [Environment]::GetFolderPath('UserProfile').TrimEnd('\')
    $documents = [Environment]::GetFolderPath('MyDocuments').TrimEnd('\')
    $documentsRelative = 'Documents'
    if ($documents.StartsWith("$userProfile\", [StringComparison]::OrdinalIgnoreCase)) {
        $documentsRelative = $documents.Substring($userProfile.Length + 1).Replace('\', '/')
    }

    $locations = @(@{ id = 'home'; label = 'Home'; path = '/host/home'; kind = 'home' })
    $volumes = @("      - type: bind`n        source: $(ConvertTo-YamlString $userProfile)`n        target: /host/home")
    $drives = Get-PSDrive -PSProvider FileSystem | Where-Object { $_.Root -match '^[A-Za-z]:\\$' -and -not $_.DisplayRoot }
    foreach ($drive in $drives) {
        $letter = $drive.Name.ToLowerInvariant()
        if (-not (Test-Path $drive.Root)) { continue }
        $locations += @{ id = "drive-$letter"; label = "$($drive.Name.ToUpperInvariant()):"; path = "/host/drives/$letter"; kind = 'drive' }
        $volumes += "      - type: bind`n        source: $(ConvertTo-YamlString $drive.Root)`n        target: /host/drives/$letter"
    }
    $json = ($locations | ForEach-Object { [ordered]@{ id = $_.id; label = $_.label; path = $_.path; kind = $_.kind } }) |
        ConvertTo-Json -Compress -Depth 3
    if (-not $json.StartsWith('[')) { $json = "[$json]" }

    $text = @(
        '# Generated by vault.ps1. Do not edit; it is rewritten on install, update and start.'
        'services:'
        '  vault:'
        '    environment:'
        '      HOME: /var/lib/resono-vault'
        "      RESONO_VAULT_DEVICE_LOCATIONS: $(ConvertTo-YamlString $json)"
        "      RESONO_VAULT_DOCUMENTS_FOLDER: $(ConvertTo-YamlString $documentsRelative)"
        '    volumes:'
    ) + $volumes
    Write-Utf8File $FoldersFile (($text -join "`n") + "`n")
}

function Import-Image {
    foreach ($name in @('resono-labs-vault.tar.zst', 'resono-labs-vault.tar.gz')) {
        $image = Join-Path (Join-Path $PackageDir 'images') $name
        if (Test-Path $image) {
            & docker load -i $image
            if ($LASTEXITCODE -ne 0) { throw 'Docker could not load the Vault image.' }
            return
        }
    }
}

function Get-SetupLink {
    $credential = (& docker compose --env-file $EnvFile -f $ComposeFile exec -T vault python -m app.vault_runtime.package_runtime show-setup).Trim()
    if ($LASTEXITCODE -ne 0 -or -not $credential) { throw 'Vault is not running yet. Run .\vault.ps1 start first.' }
    return "https://127.0.0.1:8765/identity/setup/start?credential=$credential"
}

function Backup-ExistingData {
    # Before a new image starts on existing data: database dump and Vault data (keys, files,
    # extensions, config) into backups\<time>\, like scripts/vault_package.py backup.
    & docker volume inspect resono-vault-postgres-data *> $null
    if ($LASTEXITCODE -ne 0) { return }
    try { Invoke-Compose stop vault *> $null } catch { }
    Invoke-Compose up -d --wait --no-deps postgres
    $stamp = (Get-Date).ToUniversalTime().ToString('yyyyMMddTHHmmssZ')
    $destination = Join-Path (Join-Path $PackageDir 'backups') $stamp
    New-Item -ItemType Directory -Force -Path $destination | Out-Null
    Invoke-Compose exec -T postgres sh -ec ('umask 077; pg_dump -U vault_runtime -d vault --format=custom -f /tmp/vault-backup.dump; ' +
        'tar czf /tmp/vault-backup.tar.gz --exclude=config/database-url --exclude=config/local-api-token ' +
        '-C /vault-config keys private extensions config')
    Invoke-Compose cp postgres:/tmp/vault-backup.dump (Join-Path $destination 'vault.dump')
    Invoke-Compose cp postgres:/tmp/vault-backup.tar.gz (Join-Path $destination 'vault-data.tar.gz')
    Invoke-Compose exec -T postgres rm -f /tmp/vault-backup.dump /tmp/vault-backup.tar.gz
    $schemaVersion = 0
    $hasTable = (Invoke-Compose exec -T postgres psql -U vault_runtime -d vault -Atc "SELECT to_regclass('vault_private.schema_migrations') IS NOT NULL" | Out-String).Trim()
    if ($hasTable -eq 't') {
        $schemaVersion = [int](Invoke-Compose exec -T postgres psql -U vault_runtime -d vault -Atc 'SELECT coalesce(max(version), 0) FROM vault_private.schema_migrations' | Out-String).Trim()
    }
    $manifest = [ordered]@{
        createdAt = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        format = 1
        schemaVersion = $schemaVersion
        sha256 = [ordered]@{
            'vault-data.tar.gz' = (Get-FileHash -Algorithm SHA256 (Join-Path $destination 'vault-data.tar.gz')).Hash.ToLowerInvariant()
            'vault.dump' = (Get-FileHash -Algorithm SHA256 (Join-Path $destination 'vault.dump')).Hash.ToLowerInvariant()
        }
    }
    Write-Utf8File (Join-Path $destination 'manifest.json') (($manifest | ConvertTo-Json) + "`n")
    Write-Host "Backup of your existing Vault data: $destination"
}

switch ($Command) {
    { $_ -in 'install', 'update' } {
        Assert-Docker
        Import-Image
        $lan = Set-Lan $Address
        Set-Folders
        Backup-ExistingData
        Invoke-Compose up -d --wait
        Write-Host 'Vault is ready for your computer and local network.'
        Write-Host "Computer: https://127.0.0.1:8765"
        Write-Host "Phone:    https://${lan}:8765"
        if ($Command -eq 'install') {
            $link = Get-SetupLink
            Write-Host "Opening your one-time setup link: $link"
            Start-Process $link
        }
    }
    'setup' {
        Assert-Docker
        $link = Get-SetupLink
        Write-Host $link
        Start-Process $link
    }
    'enable-lan' {
        Assert-Docker
        $lan = Set-Lan $Address
        Set-Folders
        Invoke-Compose up -d --wait
        Write-Host "Phone: https://${lan}:8765"
    }
    'start' {
        Assert-Docker
        Set-Folders
        Invoke-Compose up -d --wait
    }
    'stop' { Assert-Docker; Invoke-Compose stop }
    'status' { Assert-Docker; Invoke-Compose ps }
    'logs' { Assert-Docker; Invoke-Compose logs --tail 200 vault bridge postgres }
    'uninstall' {
        Assert-Docker
        Invoke-Compose down --remove-orphans
        Write-Host 'Vault was removed. Your saved data was preserved.'
    }
}
